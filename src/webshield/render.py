"""Pure renderers for validated WebShield policy models."""

from __future__ import annotations

from .policy import SecurityPolicy


_DISABLED_PHP_FUNCTIONS = "exec,passthru,shell_exec,system,proc_open,popen,pcntl_exec"


def render_all(policy: SecurityPolicy) -> dict[str, str]:
    """Render stable relative paths and contents without I/O or subprocesses."""
    fragments = {
        "nginx/webshield.conf": _nginx_fragment(policy),
        "systemd/nginx/webshield-hardening.conf": _nginx_systemd_fragment(policy),
        "systemd/app/webshield-hardening.conf": _app_systemd_fragment(policy),
        "systemd/upload/webshield-hardening.conf": _upload_systemd_fragment(policy),
    }
    if policy.php.enabled:
        fragments["php-fpm/webshield.conf"] = _php_fpm_fragment(policy)
    return fragments


def _nginx_fragment(policy: SecurityPolicy) -> str:
    server = policy.server
    limits = policy.limits
    security = policy.security
    listen = f"listen {server.listen_port};"
    certificate_lines = ""
    if server.tls:
        listen = f"listen {server.listen_port} ssl;"
        certificate_lines = (
            f"    ssl_certificate {server.certificate_path};\n"
            f"    ssl_certificate_key {server.certificate_key_path};\n"
            "    ssl_protocols TLSv1.2 TLSv1.3;\n"
        )

    locations = [
        "    location / {\n"
        "        try_files $uri $uri/ =404;\n"
        "    }\n"
    ]
    if security.deny_hidden_files:
        locations.append(
            "    location ~ /\\. {\n"
            "        deny all;\n"
            "        access_log off;\n"
            "        log_not_found off;\n"
            "    }\n"
        )
    if security.deny_script_execution_in_uploads:
        extensions = "|".join(extension.removeprefix(".") for extension in policy.php.allowed_extensions)
        locations.append(
            f"    location ~* ^/uploads/.*\\.(?:{extensions})$ {{\n"
            "        return 404;\n"
            "    }\n"
        )
    if policy.php.enabled:
        locations.append(
            "    location ~ \\.php$ {\n"
            "        try_files $uri =404;\n"
            "        include fastcgi_params;\n"
            "        fastcgi_param SCRIPT_FILENAME $document_root$fastcgi_script_name;\n"
            f"        fastcgi_pass unix:{policy.php.socket_path};\n"
            "    }\n"
        )
    else:
        locations.append("    location ~ \\.php$ {\n        return 404;\n    }\n")

    return (
        "# Generated by WebShield. Include inside the nginx http {} context.\n"
        f"limit_req_zone $binary_remote_addr zone=webshield_per_ip:10m rate={limits.request_rate_per_minute}r/m;\n\n"
        "server {\n"
        f"    {listen}\n"
        f"    server_name {server.server_name};\n"
        f"    root {server.document_root};\n"
        f"    client_max_body_size {limits.max_body_size};\n"
        "    server_tokens off;\n"
        "    limit_req zone=webshield_per_ip burst=20 nodelay;\n"
        f"{certificate_lines}"
        "    add_header X-Content-Type-Options \"nosniff\" always;\n"
        "    add_header X-Frame-Options \"DENY\" always;\n"
        "    add_header Referrer-Policy \"strict-origin-when-cross-origin\" always;\n"
        "    add_header Content-Security-Policy \"default-src 'self'; object-src 'none'; base-uri 'self'; frame-ancestors 'none'\" always;\n\n"
        f"{''.join(locations)}"
        "}\n"
    )


def _php_fpm_fragment(policy: SecurityPolicy) -> str:
    command_restriction = ""
    if not policy.isolation.app.command_execution:
        command_restriction = f"php_admin_value[disable_functions] = {_DISABLED_PHP_FUNCTIONS}\n"
    return (
        "; Generated by WebShield. Include in an existing non-root PHP-FPM pool.\n"
        "php_admin_flag[expose_php] = off\n"
        f"php_admin_value[open_basedir] = {policy.server.document_root}:/tmp\n"
        f"{command_restriction}"
    )


def _systemd_baseline(title: str) -> str:
    return (
        f"# Generated by WebShield for {title}. Review against runtime requirements.\n"
        "[Service]\n"
        "NoNewPrivileges=true\n"
        "PrivateTmp=true\n"
        "PrivateDevices=true\n"
        "ProtectHome=true\n"
        "ProtectKernelTunables=true\n"
        "ProtectKernelModules=true\n"
        "ProtectControlGroups=true\n"
        "RestrictSUIDSGID=true\n"
        "LockPersonality=true\n"
    )


def _nginx_systemd_fragment(policy: SecurityPolicy) -> str:
    return (
        _systemd_baseline("NGINX")
        + "ProtectSystem=strict\n"
        + f"ReadOnlyPaths={policy.server.document_root}\n"
        f"ReadOnlyPaths={policy.php.socket_path}\n"
    )


def _app_systemd_fragment(policy: SecurityPolicy) -> str:
    app = policy.isolation.app
    return (
        _systemd_baseline("application service")
        + f"User={app.service_user}\n"
        + f"Group={app.service_user}\n"
        + "ProtectSystem=strict\n"
        + f"{_systemd_paths('ReadOnlyPaths', app.read_only_paths)}"
        + f"{_systemd_paths('ReadWritePaths', app.read_write_paths)}"
        + f"{_systemd_paths('ReadWritePaths', app.allowed_socket_paths)}"
        f"{_network_rules(app.outbound_network)}"
    )


def _upload_systemd_fragment(policy: SecurityPolicy) -> str:
    upload = policy.isolation.upload
    return (
        _systemd_baseline("upload processing service")
        + f"User={upload.service_user}\n"
        + f"Group={upload.service_user}\n"
        + "ProtectSystem=strict\n"
        + f"{_systemd_paths('ReadOnlyPaths', upload.read_only_paths)}"
        + f"{_systemd_paths('ReadWritePaths', upload.read_write_paths)}"
        f"{_network_rules(upload.outbound_network)}"
    )


def _systemd_paths(directive: str, paths: tuple[str, ...]) -> str:
    return "".join(f"{directive}={path}\n" for path in paths)


def _network_rules(mode: str) -> str:
    if mode == "none":
        return "IPAddressDeny=any\n"
    return "IPAddressDeny=any\nIPAddressAllow=127.0.0.0/8\nIPAddressAllow=::1/128\n"
